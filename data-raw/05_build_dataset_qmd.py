"""Quarto generation for the per-dataset pages under docs/datasets/.

A standalone script (``make pages``, and last in ``make data-build``); the
other build steps never import it. Reads the shipped metadata and rewrites
every dataset page plus the datasets index.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from string import Template
from typing import TYPE_CHECKING

from pharmadata._core.data import (
    COLLECTIONS,
    Collection,
    DatasetMetaEntry,
    raw_meta,
)

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

PKG = Path(__file__).resolve().parents[1]
DOCS = PKG / "docs"
DATASETS = DOCS / "datasets"

# Prepended to every generated page.
GENERATED_COMMENT = (
    "<!-- Generated by data-raw/05_build_dataset_qmd.py - do not edit. -->"
)

# Nav order on the datasets index: these first, pharmaverse before the pilot;
# any other discovered collection follows in alphabetical order, never dropped.
INDEX_ORDER = ("pharmaverseadam", "pharmaversesdtm", "cdiscpilotadam", "cdiscpilotsdtm")


def _collection_dir(collection: str) -> str:
    """Numeric-prefixed directory name so the sidebar follows INDEX_ORDER.

    great-docs strips the numeric prefix when copying to the build tree, so the
    published URL stays ``<collection>/`` while the sidebar keeps the intended
    order instead of sorting alphabetically.
    """
    if collection in INDEX_ORDER:
        return f"{INDEX_ORDER.index(collection) + 1:02d}-{collection}"
    return collection


# One dataset page. $-placeholders only; the Python cells keep their own braces.
PAGE_TEMPLATE = Template(
    """\
---
title: $name
---

$generated_comment

# $name

## $label
$structure_block
```{python}
from pharmadata import $collection

meta = $collection.meta($name_repr)
print(f"Rows: {meta.number_rows:,}  Columns: {meta.number_columns}")
```

### Variables

<details>
<summary>Show variable specs</summary>

```{python}
$collection.meta($name_repr).specs
```

</details>

### Examples

```{python}
from great_docs import $widget
from pharmadata import $collection

$widget($collection.$name.head(10))
```
"""
)

# The datasets landing page: a header plus one block per collection.
INDEX_TEMPLATE = Template(
    """\
---
title: Datasets
---

# Datasets

$total datasets across $n_collections collections, loaded as polars DataFrames.
$collection_blocks"""
)

# One collection section on the index page.
COLLECTION_BLOCK_TEMPLATE = Template(
    """\

## $title

$n datasets from [$source]($url).

| Dataset | Label | Rows | Columns |
|:--|:--|--:|--:|
$rows
"""
)

# One row of the collection table.
ROW_TEMPLATE = Template(
    "| [$name]($collection/$name.html) | $label | $n_rows | $n_cols |"
)


def md(text: object) -> str:
    """Escape a value for use inside a markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _structure_block(entry: DatasetMetaEntry) -> str:
    """The optional Structure line, with blank lines around it when present."""
    structure = entry.get("structure")
    if not structure:
        return ""
    return f"\nStructure: `{structure}`\n"


def render_page(collection: str, name: str, entry: DatasetMetaEntry) -> str:
    """Render one dataset page as a single string."""
    return PAGE_TEMPLATE.substitute(
        name=name,
        generated_comment=GENERATED_COMMENT,
        label=entry["label"],
        structure_block=_structure_block(entry),
        collection=collection,
        name_repr=repr(name),
        widget="tbl_explorer",
    )


def write_page(
    collection: str,
    name: str,
    entry: DatasetMetaEntry,
    datasets: Path = DATASETS,
) -> None:
    """Generate the page of one dataset under docs/datasets/<collection>/."""
    out = datasets / _collection_dir(collection) / f"{name}.qmd"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_page(collection, name, entry), encoding="utf-8", newline="\n")


def _collection_rows(collection: str, all_meta: dict[str, DatasetMetaEntry]) -> str:
    """The table rows for one collection, newline-joined."""
    return "\n".join(
        ROW_TEMPLATE.substitute(
            name=name,
            collection=collection,
            label=md(all_meta[name]["label"]),
            n_rows=f"{all_meta[name]['n_rows']:,}",
            n_cols=len(all_meta[name]["columns"]),
        )
        for name in sorted(all_meta)
    )


def write_index(
    metas: Mapping[str, dict[str, DatasetMetaEntry]],
    collections: Mapping[str, Collection] = COLLECTIONS,
    datasets: Path = DATASETS,
) -> None:
    """Generate docs/datasets/index.qmd: every dataset grouped by collection."""
    blocks: list[str] = []
    ordered = [c for c in INDEX_ORDER if c in metas]
    ordered += [c for c in sorted(metas) if c not in INDEX_ORDER]
    for collection in ordered:
        spec = collections[collection]
        all_meta = metas[collection]
        blocks.append(
            COLLECTION_BLOCK_TEMPLATE.substitute(
                title=spec.title,
                n=len(all_meta),
                source=spec.source,
                url=spec.url,
                rows=_collection_rows(collection, all_meta),
            )
        )
    text = INDEX_TEMPLATE.substitute(
        total=sum(len(meta) for meta in metas.values()),
        n_collections=len(metas),
        collection_blocks="".join(blocks),
    )
    (datasets / "index.qmd").write_text(text, encoding="utf-8", newline="\n")


def main(
    collections: Mapping[str, Collection] = COLLECTIONS,
    datasets: Path = DATASETS,
    include: Mapping[str, Iterable[str] | None] | None = None,
    exclude: Mapping[str, Iterable[str] | None] | None = None,
    limit: int | None = None,
) -> None:
    """Regenerate dataset pages under docs/datasets/ from the shipped metadata.

    *include* and *exclude* filter which datasets are rendered, keyed by
    collection name. For *include*, ``None`` (or an absent key) means every
    dataset in that collection; a list pins the datasets to keep. When
    *include* is given, only collections named in it are rendered at all.
    For *exclude*, ``None`` means every dataset in that collection is
    skipped; a list names the datasets to drop. *limit* caps the number of
    datasets rendered per collection (the first N alphabetically). With no
    filter and no limit every dataset of every collection is rendered.
    """
    metas = {collection: raw_meta(collection) for collection in collections}
    # when include is given, only collections named in it are rendered at all
    if include is not None:
        metas = {c: m for c, m in metas.items() if c in include}
    rendered: dict[str, dict[str, DatasetMetaEntry]] = {}
    for collection, all_meta in metas.items():
        names = _filter_datasets(collection, all_meta, include, exclude)
        if limit is not None:
            names = names[:limit]
        for name in names:
            write_page(collection, name, all_meta[name], datasets=datasets)
        if names:
            rendered[collection] = {name: all_meta[name] for name in names}
    write_index(rendered, collections=collections, datasets=datasets)


def _filter_datasets(
    collection: str,
    all_meta: Mapping[str, DatasetMetaEntry],
    include: Mapping[str, Iterable[str] | None] | None,
    exclude: Mapping[str, Iterable[str] | None] | None,
) -> list[str]:
    """The dataset names of *collection* to render, after include/exclude."""
    names = set(all_meta)
    if include is not None and collection in include:
        allowed = include[collection]
        if allowed is not None:
            names &= set(allowed)
    if exclude is not None and collection in exclude:
        blocked = exclude[collection]
        names = set() if blocked is None else names - set(blocked)
    return sorted(names)


def _parse_filter(specs: list[str]) -> dict[str, list[str] | None]:
    """Parse ``collection`` or ``collection:name1,name2`` CLI specs into a dict.

    A bare collection name means "every dataset in it" (``None``); a name list
    pins the datasets. Used by both ``--include`` and ``--exclude``.
    """
    parsed: dict[str, list[str] | None] = {}
    for spec in specs:
        collection, sep, names = spec.partition(":")
        parsed[collection] = names.split(",") if sep else None
    return parsed


def _main(argv: list[str] | None = None) -> None:
    """CLI entry: regenerate dataset pages, optionally filtered."""
    parser = argparse.ArgumentParser(
        prog="python data-raw/05_build_dataset_qmd.py",
        description="Generate the per-dataset Quarto pages and the datasets index.",
    )
    parser.add_argument(
        "--include",
        action="append",
        default=[],
        metavar="SPEC",
        help="render only these (collection[:dataset,dataset]); repeatable",
    )
    parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        metavar="SPEC",
        help="skip these (collection[:dataset,dataset]); repeatable",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        metavar="N",
        help="render at most N datasets per collection (alphabetical)",
    )
    args = parser.parse_args(argv)
    main(
        include=_parse_filter(args.include) or None,
        exclude=_parse_filter(args.exclude) or None,
        limit=args.limit,
    )


if __name__ == "__main__":
    _main()
